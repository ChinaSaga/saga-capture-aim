inline const char* gpuNameByPciId(unsigned vendorId, unsigned deviceId)
{
    for (const GpuIdEntry& e : kGpuIds)
        if (e.vendor == (unsigned short)vendorId && e.device == (unsigned short)deviceId)
            return e.name;
    return nullptr;
}

// 名字里有没有 3 位以上的型号数字（老核显在 pci.ids 里只有泛称，不能拿它覆盖驱动名）
inline bool hasModelNumber(const std::string& text)
{
    int run = 0;
    for (char c : text)
    {
        if (c >= '0' && c <= '9') { if (++run >= 3) return true; }
        else run = 0;
    }
    return false;
}

// 驱动名里的型号数字是否都能在硬件名里找到
inline bool modelNumbersMatch(const std::string& driverName, const std::string& hwName)
{
    const size_t n = driverName.size();
    for (size_t i = 0; i < n; )
    {
        if (!(driverName[i] >= '0' && driverName[i] <= '9')) { ++i; continue; }
        size_t j = i;
        while (j < n && driverName[j] >= '0' && driverName[j] <= '9') ++j;
        if (j - i >= 3 && hwName.find(driverName.substr(i, j - i)) == std::string::npos) return false;
        i = j;
    }
    return true;
}

// 该显示哪个名字：
//   · 硬件 ID 表里查不到 → 用驱动名（外层还有厂商品牌校验兜底）
//   · 查到了但那条名字没有 3 位以上型号数字（老核显泛称）→ 还是用驱动名
//   · 驱动名没有型号数字、或型号数字跟硬件对不上 → **注册表被改名了** → 用硬件名
//   · 对得上 → 用驱动名（它更细，比如能区分 7900 XT / XTX 这种同 ID 多型号）
inline std::string resolveModelName(unsigned vendorId, unsigned deviceId, const std::string& driverName)
{
    const char* hw = gpuNameByPciId(vendorId, deviceId);
    if (!hw) return driverName;
    const std::string hwName = hw;
    if (!hasModelNumber(hwName)) return driverName;
    if (!hasModelNumber(driverName) || !modelNumbersMatch(driverName, hwName)) return hwName;
    return driverName;
}

